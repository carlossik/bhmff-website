const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = process.cwd()
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')

test('sponsorship modal uses two custom dropdowns and keeps both field values', () => {
  const page = read('src/components/public/PublicSponsors.tsx')
  assert.match(page, /import\s*\{\s*ThemedSelect\s*\}/)
  assert.equal((page.match(/<ThemedSelect\b/g) || []).length, 2)
  assert.match(page, /value=\{form\.sponsorshipInterest\}/)
  assert.match(page, /value=\{form\.estimatedBudget\}/)
  assert.match(page, /updateForm\('sponsorshipInterest', value\)/)
  assert.match(page, /updateForm\('estimatedBudget', value\)/)
  assert.match(page, /sponsorshipContent\.primaryInterestValue/)
  assert.match(page, /Over £10,000/)
})

test('custom dropdown has a dark popup and keyboard and outside-click controls', () => {
  const select = read('src/components/common/ThemedSelect.tsx')
  assert.match(select, /role="listbox"/)
  assert.match(select, /role="option"/)
  assert.match(select, /aria-expanded=\{open\}/)
  assert.match(select, /ArrowDown/)
  assert.match(select, /ArrowUp/)
  assert.match(select, /Escape/)
  assert.match(select, /pointerdown/)
  assert.match(select, /bg-\[#10190f\]/)
  assert.match(select, /text-white/)
})
